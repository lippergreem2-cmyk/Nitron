import os


class AIBuilder:

    def write(self, filename, code):

        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        readme = f"""# {name}

Generated by Nitron

Install any required Python packages before running.
"""

        self.write(f"{name}/README.md", readme)

        return f"{name} created."


    # =========================================
    # CHATBOT
    # =========================================

    def create_chatbot(self):

        self.create_project("ai_chatbot")

        code = '''
print("Nitron AI Chatbot")

while True:

    user = input("You: ")

    if user.lower() == "exit":

        break

    print("Nitron:", "I am learning.")
'''

        self.write("ai_chatbot/main.py", code)

        return "AI Chatbot created."


