"""
Nitron AI Generator
Creates starter AI projects.
"""

import os

PROJECTS = os.path.expanduser("~/Nitron/generated_projects")

os.makedirs(PROJECTS, exist_ok=True)


def create_ai_project(name, description):

    folder = os.path.join(
        PROJECTS,
        name.replace(" ", "_").lower()
    )

    os.makedirs(folder, exist_ok=True)

    code = f'''"""
{name}
Generated by Nitron
"""

class AI:

    def __init__(self):
        self.name = "{name}"

    def run(self):

        print("Starting {{}}".format(self.name))
        print("{description}")


if __name__ == "__main__":

    AI().run()
'''

    with open(
        os.path.join(folder, "main.py"),
        "w"
    ) as file:

        file.write(code)

    return f"{name} created successfully in {folder}"


