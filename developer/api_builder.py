import os


class APIBuilder:

    def write(self, filename, code):

        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        readme = f"""# {name}

Generated by Nitron

REST API Project
"""

        self.write(f"{name}/README.md", readme)

        return f"{name} created."


    # ==========================================
    # BASIC REST API
    # ==========================================

    def create_rest_api(self):

        self.create_project("rest_api")

        code = '''
from flask import Flask, request, jsonify

app = Flask(__name__)

items = []

@app.get("/")
def home():

    return jsonify({"message":"Nitron REST API"})


@app.get("/items")
def get_items():

    return jsonify(items)


@app.post("/items")
def add_item():

    data = request.json

    items.append(data)

    return jsonify({"status":"added","item":data})


@app.put("/items/<int:index>")
def update_item(index):

    if index >= len(items):

        return jsonify({"error":"Not found"}),404

    items[index] = request.json

    return jsonify(items[index])


@app.delete("/items/<int:index>")
def delete_item(index):

    if index >= len(items):

        return jsonify({"error":"Not found"}),404

    items.pop(index)

    return jsonify({"status":"deleted"})


app.run()
'''

        self.write("rest_api/main.py", code)

        return "REST API created."


