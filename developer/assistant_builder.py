import os


class AssistantBuilder:

    def write(self, filename, code):

        os.makedirs(os.path.dirname(filename), exist_ok=True)

        with open(filename, "w", encoding="utf-8") as f:

            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        self.write(

            f"{name}/README.md",

            f"# {name}\n\nGenerated by Nitron\n"

        )

        return f"{name} created."


    # ==========================================
    # VOICE ASSISTANT
    # ==========================================

    def create_voice_assistant(self):

        self.create_project("voice_assistant")

        code = '''
print("Nitron Voice Assistant")
'''

        self.write("voice_assistant/main.py", code)

        return "Voice Assistant created."


