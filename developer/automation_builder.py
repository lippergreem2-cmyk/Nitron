import os


class AutomationBuilder:

    def write(self, filename, code):

        os.makedirs(os.path.dirname(filename), exist_ok=True)

        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        self.write(
            f"{name}/README.md",
            f"# {name}\n\nGenerated by Nitron\n"
        )

        return f"{name} created."


    # ==========================================
    # FILE ORGANIZER
    # ==========================================

    def create_file_organizer(self):

        self.create_project("file_organizer")

        code = '''
import os

print("Nitron File Organizer")
'''

        self.write("file_organizer/main.py", code)

        return "File Organizer created."


