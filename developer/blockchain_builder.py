import os


class BlockchainBuilder:

    def write(self, filename, code):

        os.makedirs(os.path.dirname(filename), exist_ok=True)

        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        self.write(
            f"{name}/README.md",
            f"# {name}\n\nGenerated by Nitron Blockchain Builder\n"
        )

        return f"{name} created."


    # ==========================================
    # BLOCKCHAIN
    # ==========================================

    def create_blockchain(self):

        self.create_project("blockchain")

        code = '''
print("Blockchain Template")
'''

        self.write("blockchain/main.py", code)

        return "Blockchain created."


