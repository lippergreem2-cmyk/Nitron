import os


class CloudBuilder:

    def write(self, filename, code):

        os.makedirs(os.path.dirname(filename), exist_ok=True)

        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        self.write(
            f"{name}/README.md",
            f"# {name}\n\nGenerated by Nitron Cloud Builder\n"
        )

        return f"{name} created."


    # ==========================================
    # AWS PROJECT
    # ==========================================

    def create_aws(self):

        self.create_project("aws_project")

        code = '''
print("AWS Project Template")
'''

        self.write("aws_project/main.py", code)

        return "AWS Project created."


