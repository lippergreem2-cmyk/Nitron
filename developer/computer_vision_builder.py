import os


class ComputerVisionBuilder:

    def write(self, filename, code):

        os.makedirs(os.path.dirname(filename), exist_ok=True)

        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        self.write(
            f"{name}/README.md",
            f"# {name}\n\nGenerated by Nitron\n"
        )

        return f"{name} created."


    # ==========================================
    # IMAGE VIEWER
    # ==========================================

    def create_image_viewer(self):

        self.create_project("image_viewer")

        code = '''
import cv2

image = cv2.imread("image.jpg")

cv2.imshow("Image", image)

cv2.waitKey(0)

cv2.destroyAllWindows()
'''

        self.write("image_viewer/main.py", code)

        return "Image Viewer created."


    # ==========================================
    # WEBCAM
    # ==========================================

    def create_webcam(self):

        self.create_project("webcam")

        code = '''
import cv2

camera = cv2.VideoCapture(0)

while True:

    ok, frame = camera.read()

    if not ok:
        break

    cv2.imshow("Camera", frame)

    if cv2.waitKey(1) == 27:
        break

camera.release()

cv2.destroyAllWindows()
'''

        self.write("webcam/main.py", code)

        return "Webcam project created."


