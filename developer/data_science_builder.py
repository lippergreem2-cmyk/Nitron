import os


class DataScienceBuilder:

    def write(self, filename, code):

        os.makedirs(os.path.dirname(filename), exist_ok=True)

        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        self.write(
            f"{name}/README.md",
            f"# {name}\n\nGenerated by Nitron Data Science Builder\n"
        )

        return f"{name} created."


    # ==========================================
    # DATA ANALYSIS
    # ==========================================

    def create_data_analysis(self):

        self.create_project("data_analysis")

        code = '''
import pandas as pd

print("Data Analysis Template")
'''

        self.write("data_analysis/main.py", code)

        return "Data Analysis created."


