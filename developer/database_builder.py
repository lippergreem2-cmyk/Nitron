import os


class DatabaseBuilder:

    def write(self, filename, code):

        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        readme = f"""# {name}

Generated by Nitron

Database project template.
"""

        self.write(f"{name}/README.md", readme)

        return f"{name} created."


    # =========================================
    # SQLITE DATABASE
    # =========================================

    def create_sqlite(self):

        self.create_project("sqlite_database")

        code = '''
import sqlite3

conn = sqlite3.connect("database.db")

cursor = conn.cursor()

cursor.execute("""
CREATE TABLE IF NOT EXISTS users(

id INTEGER PRIMARY KEY,

name TEXT,

email TEXT

)
""")

conn.commit()

conn.close()

print("Database created.")
'''

        self.write("sqlite_database/main.py", code)

        return "SQLite project created."


