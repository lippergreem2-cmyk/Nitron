import os


class DesktopBuilder:

    def write(self, filename, code):

        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)

    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        readme = f"""# {name}

Desktop application generated by Nitron.

Run:

python main.py
"""

        self.write(f"{name}/README.md", readme)

        return f"{name} created."


    # ==========================================
    # TKINTER APP
    # ==========================================

    def create_tkinter(self):

        self.create_project("tkinter_app")

        code = '''
import tkinter as tk

root = tk.Tk()

root.title("Nitron App")

root.geometry("600x400")

label = tk.Label(
    root,
    text="Welcome to Nitron Desktop",
    font=("Arial",18)
)

label.pack(pady=20)

button = tk.Button(
    root,
    text="Close",
    command=root.destroy
)

button.pack()

root.mainloop()
'''

        self.write("tkinter_app/main.py", code)

        return "Tkinter app created."


