import os


class DockerBuilder:

    def write(self, filename, code):

        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        readme = f"""# {name}

Generated by Nitron

Docker project template.
"""

        self.write(f"{name}/README.md", readme)

        return f"{name} created."


    # ==========================================
    # PYTHON DOCKER
    # ==========================================

    def create_python_container(self):

        self.create_project("python_docker")

        dockerfile = '''FROM python:3.12

WORKDIR /app

COPY . .

CMD ["python","main.py"]
'''

        main = '''print("Python Docker Container Running")
'''

        self.write("python_docker/Dockerfile", dockerfile)
        self.write("python_docker/main.py", main)

        return "Python Docker project created."


    # ==========================================
    # FLASK DOCKER
