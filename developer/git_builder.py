import os


class GitBuilder:

    def write(self, filename, code):

        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        readme = f"""# {name}

Generated by Nitron

Git project template.
"""

        self.write(f"{name}/README.md", readme)

        return f"{name} created."


    # ==========================================
    # GIT REPOSITORY
    # ==========================================

    def create_repository(self):

        self.create_project("git_repository")

        gitignore = """__pycache__/
*.pyc
.env
.venv/
node_modules/
build/
dist/
"""

        self.write("git_repository/.gitignore", gitignore)

        return "Git repository created."


    # ==========================================
    # PYTHON PROJECT
    # ==========================================

    def create_python_repo(self):

        self.create_project("python_repo")

        self.write(
            "python_repo/.gitignore",
            "__pycache__/\n*.pyc\n.venv/\n.env\n"
        )

        return "Python repository created."


