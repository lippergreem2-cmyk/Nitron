import os
import json


class LearningBuilder:

    def write(self, filename, code):

        os.makedirs(os.path.dirname(filename), exist_ok=True)

        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        self.write(
            f"{name}/README.md",
            f"# {name}\n\nGenerated by Nitron Learning Builder\n"
        )

        return f"{name} created."


    # =====================================
    # KNOWLEDGE BASE
    # =====================================

    def create_knowledge_base(self):

        self.create_project("knowledge_base")

        data = {
            "books": [],
            "websites": [],
            "notes": [],
            "documents": [],
            "skills": []
        }

        with open(
            "knowledge_base/data.json",
            "w",
            encoding="utf-8"
        ) as f:

            json.dump(data, f, indent=4)

        return "Knowledge Base created."


