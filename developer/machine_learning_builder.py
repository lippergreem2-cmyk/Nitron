import os


class MachineLearningBuilder:

    def write(self, filename, code):

        os.makedirs(os.path.dirname(filename), exist_ok=True)

        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        self.write(
            f"{name}/README.md",
            f"# {name}\n\nGenerated by Nitron\n"
        )

        return f"{name} created."


    # ==========================================
    # LINEAR REGRESSION
    # ==========================================

    def create_linear_regression(self):

        self.create_project("linear_regression")

        code = '''
from sklearn.linear_model import LinearRegression

print("Linear Regression Template")
'''

        self.write("linear_regression/main.py", code)

        return "Linear Regression project created."


