import os


class MobileBuilder:

    def write(self, filename, code):

        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)

    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        readme = f"""# {name}

Mobile project generated by Nitron.

"""

        self.write(f"{name}/README.md", readme)

        return f"{name} created."


    # ==========================================
    # FLUTTER APP
    # ==========================================

    def create_flutter(self):

        self.create_project("flutter_app")

        code = '''
import 'package:flutter/material.dart';

void main(){

  runApp(const MyApp());

}

class MyApp extends StatelessWidget{

  const MyApp({super.key});

  @override

  Widget build(BuildContext context){

    return MaterialApp(

      home: Scaffold(

        appBar: AppBar(

          title: const Text("Nitron Flutter"),

        ),

        body: const Center(

          child: Text("Hello World"),

        ),

      ),

    );

  }

}
'''

        self.write("flutter_app/main.dart", code)

        return "Flutter project created."


