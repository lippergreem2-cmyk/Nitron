import os


class OperatingSystemBuilder:

    def write(self, filename, code):

        os.makedirs(os.path.dirname(filename), exist_ok=True)

        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        self.write(
            f"{name}/README.md",
            f"# {name}\n\nGenerated by Nitron Operating System Builder\n"
        )

        return f"{name} created."


    # ==========================================
    # SHELL
    # ==========================================

    def create_shell(self):

        self.create_project("shell")

        code = '''
print("Nitron Shell")

while True:

    command = input("Nitron> ")

    if command == "exit":
        break

    print("You entered:", command)
'''

        self.write("shell/main.py", code)

        return "Shell project created."


