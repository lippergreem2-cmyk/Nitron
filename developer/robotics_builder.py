import os


class RoboticsBuilder:

    def write(self, filename, code):

        os.makedirs(os.path.dirname(filename), exist_ok=True)

        with open(filename, "w", encoding="utf-8") as f:
            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        self.write(
            f"{name}/README.md",
            f"# {name}\n\nGenerated by Nitron Robotics Builder\n"
        )

        return f"{name} created."


    # ==========================================
    # ROBOT CONTROLLER
    # ==========================================

    def create_robot_controller(self):

        self.create_project("robot_controller")

        code = '''
print("Nitron Robot Controller")
'''

        self.write("robot_controller/main.py", code)

        return "Robot Controller created."


