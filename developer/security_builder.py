import os


class SecurityBuilder:

    def write(self, filename, code):

        os.makedirs(os.path.dirname(filename), exist_ok=True)

        with open(filename, "w", encoding="utf-8") as f:

            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        self.write(
            f"{name}/README.md",
            f"# {name}\n\nGenerated by Nitron\n"
        )

        return f"{name} created."


    # ==========================================
    # PASSWORD HASHER
    # ==========================================

    def create_password_hasher(self):

        self.create_project("password_hasher")

        code = '''
import hashlib

password = input("Password: ")

hashed = hashlib.sha256(password.encode()).hexdigest()

print("SHA256:", hashed)
'''

        self.write("password_hasher/main.py", code)

        return "Password Hasher created."


    # ==========================================
    # FILE HASHER
    # ==========================================

    def create_file_hasher(self):

        self.create_project("file_hasher")

        code = '''
import hashlib

filename = input("File: ")

with open(filename,"rb") as f:

    print(hashlib.sha256(f.read()).hexdigest())
'''

        self.write("file_hasher/main.py", code)

        return "File Hasher created."


    # ==========================================
    # RANDOM PASSWORD
    # ==========================================

    def create_password_generator(self):

        self.create_project("password_generator")

        code = '''
import secrets
import string

alphabet = string.ascii_letters + string.digits

password = "".join(
    secrets.choice(alphabet)
    for _ in range(20)
)

print(password)
'''

        self.write("password_generator/main.py", code)

        return "Password Generator created."


