import os


class TestingBuilder:

    def write(self, filename, code):

        os.makedirs(os.path.dirname(filename), exist_ok=True)

        with open(filename, "w", encoding="utf-8") as f:

            f.write(code)


    def create_project(self, name):

        os.makedirs(name, exist_ok=True)

        self.write(
            f"{name}/README.md",
            f"# {name}\n\nGenerated by Nitron\n"
        )

        return f"{name} created."


    # ==========================================
    # UNIT TEST
    # ==========================================

    def create_unit_test(self):

        self.create_project("unit_test")

        code = '''
import unittest

class TestMath(unittest.TestCase):

    def test_add(self):

        self.assertEqual(2+2,4)

if __name__=="__main__":

    unittest.main()
'''

        self.write("unit_test/test_math.py", code)

        return "Unit Test created."


